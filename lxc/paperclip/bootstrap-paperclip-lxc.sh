#!/usr/bin/env bash
# Bootstrap the Paperclip orchestrator inside the LXC container (ct 254,
# lab-pve1) created by Terraform.
#
# Run from the workstation after `terraform apply`:
#   TS_AUTHKEY=... GIT_TOKEN=... \
#   OPENCODE_SERVER_USERNAME=... OPENCODE_SERVER_PASSWORD=... \
#   ./lxc/paperclip/bootstrap-paperclip-lxc.sh
#
# opencode gateway auth (default free models like big-pickle) is copied
# automatically from $HOME/.local/share/opencode/auth.json — no API key
# needed.
#
# Idempotent: safe to re-run.
#
# Secrets are piped to the remote host over SSH stdin, never embedded in a
# command line — a command-line arg is visible to any local user on ct254 via
# `ps auxww` for as long as the process runs; stdin isn't.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REMOTE_PROVISION_SCRIPT="$SCRIPT_DIR/remote-provision.sh"

CT_HOST="${CT_HOST:-root@192.168.0.54}"
OPENCODE_VERSION="${OPENCODE_VERSION:-1.18.25}"

# TS_AUTHKEY is only needed if the container has not joined the tailnet yet,
# so a re-run against an already-joined container can leave it unset.
if [ -z "${TS_AUTHKEY:-}" ]; then
  log "no TS_AUTHKEY — needed only if this container has not joined the tailnet"
fi
: "${GIT_TOKEN:?set GIT_TOKEN (Forgejo token — verify it is scoped to lab/homelab only, not account-wide)}"
: "${OPENCODE_SERVER_USERNAME:?set OPENCODE_SERVER_USERNAME (web basic auth)}"
: "${OPENCODE_SERVER_PASSWORD:?set OPENCODE_SERVER_PASSWORD (web basic auth)}"

# Two scoped kubeconfigs, generated by generate-kubeconfig.sh.
OPS_KUBECONFIG_SRC="${OPS_KUBECONFIG_SRC:-$SCRIPT_DIR/../../temp/paperclip-ops.kubeconfig}"
DEPLOY_KUBECONFIG_SRC="${DEPLOY_KUBECONFIG_SRC:-$SCRIPT_DIR/../../temp/paperclip-deploy.kubeconfig}"
AUTH_SRC="${AUTH_SRC:-$HOME/.local/share/opencode/auth.json}"

log() { echo "[bootstrap] $*"; }

# accept-new: ct254 has no entry in known_hosts on first run. Trust on
# first use, then pin — BatchMode alone would refuse and abort.
SSH=(ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new)
SCP=(scp -q -o BatchMode=yes -o StrictHostKeyChecking=accept-new)

push_kubeconfigs() {
  "${SSH[@]}" "$CT_HOST" 'mkdir -p /root/.kube'
  local src name
  for pair in "$OPS_KUBECONFIG_SRC:ops-config" "$DEPLOY_KUBECONFIG_SRC:deploy-config"; do
    src="${pair%:*}"; name="${pair##*:}"
    if [ -f "$src" ]; then
      "${SCP[@]}" "$src" "$CT_HOST:/root/.kube/$name"
      log "kubeconfig copied ($src -> $name)"
    else
      log "no kubeconfig at $src — that agent will start without cluster access"
    fi
  done
}

push_opencode_auth() {
  if [ -f "$AUTH_SRC" ]; then
    "${SSH[@]}" "$CT_HOST" 'install -d /root/.local/share/opencode'
    "${SCP[@]}" "$AUTH_SRC" "$CT_HOST:/root/.local/share/opencode/auth.json"
    log "opencode gateway auth staged for the service user"
  else
    log "no auth.json at $AUTH_SRC — run 'opencode auth login' on the workstation first"
  fi
}

provision_remote() {
  log "running remote provisioning script"
  # %q shell-quotes each value so tokens with special characters survive the
  # round trip intact; the whole block is piped over stdin, so none of this
  # ever appears as a ct254 process argument.
  {
    printf 'export OPENCODE_VERSION=%q\n' "$OPENCODE_VERSION"
    printf 'export TS_AUTHKEY=%q\n' "$TS_AUTHKEY"
    printf 'export GIT_TOKEN=%q\n' "$GIT_TOKEN"
    printf 'export OPENCODE_SERVER_USERNAME=%q\n' "$OPENCODE_SERVER_USERNAME"
    printf 'export OPENCODE_SERVER_PASSWORD=%q\n' "$OPENCODE_SERVER_PASSWORD"
    cat "$REMOTE_PROVISION_SCRIPT"
  } | "${SSH[@]}" "$CT_HOST" bash -s
}

push_kubeconfigs
push_opencode_auth
provision_remote

TS_IP="$("${SSH[@]}" "$CT_HOST" 'tailscale ip -4' | head -1)"
echo "[done] Paperclip bootstrapped. Reach it at http://${TS_IP}:3100 via Tailscale"
echo "       or http://192.168.0.54:3100 on the LAN."
echo "[next] if the board is unclaimed, read its admin invite URL from ct254:"
echo "       ssh root@192.168.0.54 \"journalctl -u paperclip | grep -m1 'Invite URL'\""
